    private fun buildPassagesExposition(q: String, chunks: List<NativeSearchResult>): String {
        val sb = StringBuilder()

        chunks.forEachIndexed { index, chunk ->
            val ref = chunk.canonicalRef
            val testament = if (chunk.testament.contains("Новый")) "Нового Завета" else "Ветхого Завета"

            sb.append("📌 **[$ref]** ($testament):\n")

            // Очищаем и форматируем текст отрывка для лаконичного цитирования
            val cleanText = chunk.text
                .replace(Regex("\\s+"), " ")
                .trim()

            val quote = if (cleanText.length > 220) {
                cleanText.take(215) + "..."
            } else {
                cleanText
            }

            sb.append("«$quote»\n")

            // Индивидуальный богословский комментарий
            val comment = explainPassageInsight(ref, cleanText, q, index)
            sb.append(comment)

            if (index < chunks.lastIndex) {
                sb.append("\n\n")
            }
        }

        return sb.toString()
    }

    private fun explainPassageInsight(ref: String, text: String, q: String, index: Int): String {
        val t = text.lowercase()

        // 1. Тематические привязки по ключевым словам отрывка
        if (t.contains("войн") || t.contains("брань") || t.contains("полк") || t.contains("сражен")) {
            return when (index % 3) {
                0 -> "Этот исторический отрывок повествует о суровых испытаниях военных лет, свидетельствуя о том, что ход исторических битв находится под суверенным Божьим промыслом."
                1 -> "Писание здесь подчеркивает тяжесть военных конфликтов, напоминая о ценности мира и необходимости упования на Господа даже в дни грозных столкновений."
                else -> "В этих строках раскрывается библейское свидетельство о вооруженном противостоянии, побуждая человека ценить мир и искать Божьей защиты."
            }
        }

        if (t.contains("левиафан") || ref.contains("Иов 41")) {
            return "Описание могущественного левиафана в книге Иова являет непостижимую премудрость и силу Творца, напоминая человеку о смирении перед величием Божьим."
        }

        if (ref.contains("Иов 24")) {
            return "Иов размышляет о тайнах земного правосудия и видимом благоденствии нечестивых, твердо веря, что окончательный суд принадлежит Богу."
        }

        if (ref.contains("Римлянам") && ref.contains("13:14")) {
            return "Апостол Павел дает здесь практическое правило победы над искушениями: «облечься в Господа Иисуса Христа» — жить в общении со Спасителем и сознательно не потворствовать греховным страстям."
        }

        if (ref.contains("Иоанна") && ref.contains("2:16")) {
            return "Апостол Иоанн предостерегает от трех главных соблазнов мира сего: похоти плоти, похоти очей и гордости житейской, напоминая, что исполняющий волю Божью пребывает вовек."
        }

        if (ref.contains("Евреям") && ref.contains("7:")) {
            return "Послание к Евреям объясняет духовный смысл священства Мелхиседека: служение Христа превосходит временный левитский закон и пребывает непреложно вовеки."
        }

        // 2. Классификация по библейским книгам и жанрам
        val prefix = when (index % 3) {
            0 -> "Свидетельство этого отрывка:"
            1 -> "В контексте данной священной книги:"
            else -> "Духовный смысл данного фрагмента:"
        }

        return when {
            ref.contains("Царств") || ref.contains("Паралипоменон") || ref.contains("Судей") || ref.contains("Иисус Навин") -> {
                "$prefix летопись Ветхого Завета раскрывает конкретные исторические события и судьбы царей и воинов, демонстрируя последствия верности или отступления народа от заповедей Господних."
            }
            ref.contains("Псал") -> {
                "$prefix Псалмопевец выражает живое упование верующей души, находящей в Господе свое непоколебимое прибежище, щит и надежду среди любых жизненных бурь."
            }
            ref.contains("Притч") || ref.contains("Екклесиаст") -> {
                "$prefix Книга мудрости преподает практическое благоразумие, призывая хранить сердце чистым, удаляться от путей зла и уповать на Божье водительство."
            }
            ref.contains("Исаи") || ref.contains("Иерем") || ref.contains("Иезек") || ref.contains("Даниил") -> {
                "$prefix Пророческое слово обличает неправду и призывает народ к глубокому покаянию, указывая на неизбежность Божьего суда и обетование грядущего мира."
            }
            ref.contains("Матфе") || ref.contains("Марк") || ref.contains("Лук") || ref.contains("Иоан") -> {
                "$prefix В Евангелии Господь открывает совершенную любовь и истину Нового Завета, призывая Своих последователей к кротости, прощению и жизни по вере."
            }
            ref.contains("Коринф") || ref.contains("Галат") || ref.contains("Ефес") || ref.contains("Филип") || ref.contains("Колос") -> {
                "$prefix Апостольское послание содержит прямое духовное наставление общине верующих, укрепляя их в вере, взаимной любви и святости жизни."
            }
            ref.contains("Откровени") -> {
                "$prefix Тайнозритель возвещает окончательное торжество Божьей правды и Царства Христова над всеми силами тления и тьмы."
            }
            else -> {
                when (index % 3) {
                    0 -> "Этот священный текст прямо раскрывает рассматриваемую тему, призывая читателя вникать в Слово Божье и сообразовывать свою жизнь с Его истиной."
                    1 -> "Отрывок помогает глубже осознать замысел Божий, вдохновляя хранить стойкость и упование на Господа во всяких обстоятельствах."
                    else -> "Данные библейские строки напоминают о непреложности Божьих обетований и важности чистого сердца пред Творцом."
                }
            }
        }
    }


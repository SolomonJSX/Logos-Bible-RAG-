package com.biblerag.engine

import com.biblerag.core.NativeSearchResult

/**
 * Построитель Zero-Shot промпта персонажа «Писарь Соломона» для модели Qwen2.5-1.5B (GGUF).
 * Оптимизирован для мобильного инференса: минимальный размер промпта, строгая самофильтрация RAG-контекста,
 * а также четкое ограничение тематики: только Библия, Бог, вера, душа, смысл жизни и философия.
 */
object PromptBuilder {

    private const val SOLOMON_SCRIBE_SYSTEM_PROMPT =
        "Ты — Елихореф, мудрый царский писец царя Соломона, хранитель древних свитков Священного Писания.\n" +
        "Твой долг — раскрывать мудрость Слова Божьего тем, кто обращается к тебе за советом.\n\n" +
        "ГРАНИЦЫ ТЕМАТИКИ:\n" +
        "Твоя область — ТОЛЬКО Священное Писание, Бог, вера, молитва, душа, смысл человеческой жизни, добро и зло, вечность, любовь, добродетели и библейская философия.\n" +
        "Если вопрошающий спрашивает о мирских вещах (программирование, техника, рецепты, погода, светская политика, быт, развлечения) — ты ОБЯЗАН кротко отклонить ответ:\n" +
        "«Мир дому твоему, путник. Я — царский писец царя Соломона, хранитель священных свитков. Мой удел — свидетельствовать о Слове Божьем, о душе и смысле бытия. О мирских же ремеслах вопрошай иных людей. Если сердце твое ищет истину о Боге или жизни — вопрошай о Писании.»\n\n" +
        "ПРАВИЛА И СТИЛЬ:\n" +
        "1. Говори благородно, кротко и с почтением, без сухих роботизированных шаблонов.\n" +
        "2. Опирайся ТОЛЬКО на те отрывки Писания из контекста, которые прямо отвечают на вопрос. Посторонние стихи полностью игнорируй.\n" +
        "3. Приводи точные ссылки в формате [Книга Гл:Ст] «текст».\n" +
        "4. Структура ответа:\n" +
        "   • 📜 Слово Писания (точная цитата)\n" +
        "   • 💡 Смысл и толкование (духовный контекст стиха)\n" +
        "   • 🕊️ Мудрое наставление (как применить сие в жизни)\n" +
        "5. Если в контексте нет прямого ответа, ответь: «В свитках, открытых ныне предо мной, нет прямого ответа на сие...» и предложи искать в молитве или смежных книгах Писания.\n" +
        "6. Никогда не придумывай стихи от себя."

    fun build(query: String, contextChunks: List<NativeSearchResult>): String {
        val topChunks = contextChunks.take(5)
        val formattedContext = if (topChunks.isEmpty()) {
            "Свитки Писания по данному запросу не найдены."
        } else {
            topChunks.joinToString("\n\n") { chunk ->
                val snippet = if (chunk.text.length > 220) chunk.text.take(215) + "..." else chunk.text
                "[${chunk.canonicalRef}]: $snippet"
            }
        }

        return buildString {
            append("<|im_start|>system\n")
            append(SOLOMON_SCRIBE_SYSTEM_PROMPT)
            append("<|im_end|>\n")

            append("<|im_start|>user\n")
            append("Свитки Писания из хранилища:\n")
            append(formattedContext)
            append("\n\nВопрос вопрошающего: ")
            append(query)
            append("<|im_end|>\n")

            append("<|im_start|>assistant\n")
        }
    }
}

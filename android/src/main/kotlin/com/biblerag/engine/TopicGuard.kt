package com.biblerag.engine

sealed interface TopicCheckResult {
    object Allowed : TopicCheckResult
    data class Refusal(val message: String) : TopicCheckResult
}

/**
 * Страж тематики диалога (Scope Guard).
 * СТРОГО проверяет текст сообщения ДО запуска embedding и поиска по базе:
 * - Отсекает математические формулы, цифры (например: 2+2, 5*10).
 * - Отсекает бессмысленные короткие строки и знаки препинания.
 * - Обрабатывает приветствия без поиска по свиткам.
 * - Отсекает светские, бытовые и технические вопросы.
 * - Пропускает к embedding ТОЛЬКО вопросы о Библии, Боге, вере, душе, смысле жизни и философии.
 */
object TopicGuard {

    private val GREETING_REPLY = """
        Мир и благодать дому твоему, путник!
        
        Я — Елихореф, царский писец царя Соломона. О чем желает вопросить сердце твое: о вере, молитве, притчах, заповедях или смысле жизни? Открой мне свой вопрос, и я исследую священные свитки.
    """.trimIndent()

    private val MATH_REFUSAL = """
        Мир дому твоему, путник.
        
        Ты вопрошаешь о мирских вычислениях и земных числах. Я же — хранитель священных свитков Закона и веры. Мой удел — возвещать о Слове Божьем, о спасении души и смысле человеческого бытия.
        
        О мирских же расчетах вопрошай у иных людей. Если же сердце твое ищет истины о Боге, молитве или Писании — вопрошай, и я открою пред тобою свитки мудрости.
    """.trimIndent()

    private val SHORT_GIBBERISH_REFUSAL = """
        Мир тебе. Задай свой вопрос о Священном Писании, вере, Боге или смысле жизни полными словами, и я отыщу для тебя наставление в священных свитках.
    """.trimIndent()

    val SCRIBE_REFUSAL_MESSAGE = """
        Мир дому твоему, путник.
        
        Я — царский писец царя Соломона, хранитель священных свитков. Мой удел — свидетельствовать о Слове Всевышнего, о тайнах веры, смысле человеческого бытия и путях праведности.
        
        О мирских же ремеслах, технике, быте и суетных делах века сего вопрошай у иных людей. Если же сердце твое ищет истины о Боге, душе, надежде или Священном Писании — вопрошай, и я с радостью раскрою пред тобою мудрость свитков.
    """.trimIndent()

    // Мирские стоп-слова (IT, быт, развлечения)
    private val SECULAR_STOP_WORDS = listOf(
        "код", "программир", "python", "javascript", "java", "kotlin", "c++", "c#", "html", "css",
        "sql", "скрипт", "компиля", "сервер", "баг", "фреймворк", "компьютер", "ноутбук", "процессор",
        "видеокарт", "айфон", "смартфон", "андроид", "android", "windows", "linux", "wifi", "вайфай",
        "вай-фай", "bluetooth", "блютуз", "приложен", "пароль", "взлом", "хакер",
        "рецепт", "борщ", "пирог", "суп", "жарить", "варить", "ингредиент", "блюдо", "кастрюл",
        "сковород", "стирал", "утюг", "пылесос", "ремонт авто", "запчаст",
        "прогноз погод", "погода в", "курс доллар", "курс валют", "криптовалют", "биткоин",
        "акци", "футбол", "хоккей", "чемпионат", "матч", "лига чемпион", "гороскоп", "знак зодиак",
        "таро", "фильм", "кино", "сериал", "актер", "селебрити", "gta", "видеоигр", "играть в игру"
    )

    // Ключевые слова приветствия
    private val GREETING_WORDS = listOf(
        "привет", "здравствуй", "добрый день", "доброе утро", "добрый вечер", "мир тебе", "хай", "салам"
    )

    /**
     * Проверяет валидность запроса ДО запуска embedding и поиска по базе.
     */
    fun checkTopic(query: String): TopicCheckResult {
        val q = query.lowercase().trim()

        // 1. Проверка на математические выражения и числа (например "2+2", "5*10", "123")
        val mathPattern = Regex("""^[\s\d\+\-\*/=\^%\(\)\.,]+$""")
        if (mathPattern.matches(q) || (q.contains(Regex("""\d+[\+\-\*/]\d+""")) && !hasBiblicalAnchor(q))) {
            return TopicCheckResult.Refusal(MATH_REFUSAL)
        }

        // 2. Слишком короткие бессмысленные запросы или знаки препинания
        if (q.length < 3 || q.all { !it.isLetter() }) {
            return TopicCheckResult.Refusal(SHORT_GIBBERISH_REFUSAL)
        }

        // 3. Простое приветствие без вопроса
        if (GREETING_WORDS.any { q == it || q.startsWith("$it ") && q.length < 15 }) {
            return TopicCheckResult.Refusal(GREETING_REPLY)
        }

        // 4. Проверка на явные мирские/технические стоп-слова
        for (stopWord in SECULAR_STOP_WORDS) {
            if (q.contains(stopWord) && !hasBiblicalAnchor(q)) {
                return TopicCheckResult.Refusal(SCRIBE_REFUSAL_MESSAGE)
            }
        }

        // Запрос допущен к embedding и исследованию Писания
        return TopicCheckResult.Allowed
    }

    private fun hasBiblicalAnchor(q: String): Boolean {
        return q.contains("библи") ||
                q.contains("писани") ||
                q.contains("бог") ||
                q.contains("христ") ||
                q.contains("господ") ||
                q.contains("иисус") ||
                q.contains("грех") ||
                q.contains("заповед") ||
                q.contains("верен") ||
                q.contains("молитв") ||
                q.contains("стих") ||
                q.contains("глав")
    }
}
